import { chromium } from "playwright"
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on("pageerror", e => console.log("[pageerror]", e.message))
await page.goto("http://127.0.0.1:3090/", { waitUntil: "domcontentloaded" })
await page.waitForTimeout(2500)
await page.locator("[data-sandore-btn]").click()
await page.waitForTimeout(600)
await page.locator("[data-sandore-wf-list] [role=tab]").nth(1).click()
await page.waitForTimeout(600)
await page.getByRole("button", { name: "新增定义" }).click()
await page.waitForTimeout(800)
const nodes = page.locator(".react-flow__node")
await nodes.nth(0).dblclick()
await page.waitForTimeout(800)
const addStep = page.getByRole("button", { name: "添加步骤" })
await addStep.first().click()
await page.waitForTimeout(400)
await addStep.first().click()
await page.waitForTimeout(400)
// 回环 step2->step1
const sb = await nodes.nth(1).locator(".react-flow__handle.source").boundingBox()
const tb = await nodes.nth(0).locator(".react-flow__handle.target").boundingBox()
await page.mouse.move(sb.x + sb.width / 2, sb.y + sb.height / 2)
await page.mouse.down()
await page.mouse.move(tb.x + tb.width / 2, tb.y + tb.height / 2, { steps: 12 })
await page.mouse.up()
await page.waitForTimeout(600)
await nodes.nth(1).click()
await page.waitForTimeout(500)
const panel = page.locator("[data-sandore-dag-panel]")
// 循环区块的跳出目标下拉
const loopSel = panel.locator('[class*="loop"] select')
console.log("loop selects:", await loopSel.count())
const exitOpts = await loopSel.last().locator("option").allTextContents()
console.log("exit options:", JSON.stringify(exitOpts))
// 选择 END 时 exitTo 应为 undefined（YAML 不含该字段）——通过 YAML 预览验证
await loopSel.last().selectOption("__end__")
await page.waitForTimeout(400)
const endVal = await loopSel.last().inputValue()
console.log("exit value after END select:", endVal)
await browser.close()
